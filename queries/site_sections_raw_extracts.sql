-- Extra RAW / curated extracts behind dashboard sections 1, 3, 5, 9, 10. SELECT only.
-- Plant HZL_DEMO_05, as-of 2025-12-31, IS_BACKCAST_PERIOD='N' on every FACT table, ZSPR/ZSPN scope.
-- :MATS = the 50 material ids in data/demo_net_issue_series.csv.
-- Scope note: the series reads FACT_MATERIAL_MOVEMENT_PART_001..004 because PART_001 alone holds non-backcast
-- 261/262 postings only up to 2024-07-19 for this plant (observed: PART_001 2024-01-01..2024-07-19,
-- PART_002 ..2025-03-17, PART_003 ..2025-10-18, PART_004 ..2025-12-31).

-- A. Month-end stock for the 50 materials (data/raw/raw_stock_monthly_50.csv). Snapshots span PART_001..003.
WITH S AS (
  SELECT SNAPSHOT_DATE, MATERIAL_ID, CLOSING_QTY FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_001 WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N'
  UNION ALL
  SELECT SNAPSHOT_DATE, MATERIAL_ID, CLOSING_QTY FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_002 WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N'
  UNION ALL
  SELECT SNAPSHOT_DATE, MATERIAL_ID, CLOSING_QTY FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_003 WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N'
)
SELECT S.SNAPSHOT_DATE, COUNT(*) N, SUM(TO_DECIMAL(S.CLOSING_QTY,18,3)) QTY,
       SUM(TO_DECIMAL(S.CLOSING_QTY,18,3)*TO_DECIMAL(D.UNIT_COST_INR,18,4)) VAL,
       SUM(CASE WHEN TO_DECIMAL(S.CLOSING_QTY,18,3)<=0 THEN 1 ELSE 0 END) ZERO_STOCK
FROM S JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID=S.MATERIAL_ID
WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND S.MATERIAL_ID IN (:MATS)
GROUP BY S.SNAPSHOT_DATE ORDER BY S.SNAPSHOT_DATE;

-- B. Plant-wide RAW gross at 2025-12-31, ZSPR/ZSPN (reconciles to curated INVENTORY_KPI_MONTHLY gross)
SELECT COUNT(*) N, SUM(TO_DECIMAL(S.CLOSING_QTY,18,3)) QTY,
       SUM(TO_DECIMAL(S.CLOSING_QTY,18,3)*TO_DECIMAL(D.UNIT_COST_INR,18,4)) VAL
FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_003 S JOIN VEDANTA_POC.DIM_MATERIAL D ON D.MATERIAL_ID=S.MATERIAL_ID
WHERE S.PLANT_ID='HZL_DEMO_05' AND S.IS_BACKCAST_PERIOD='N' AND S.SNAPSHOT_DATE='2025-12-31' AND D.MATERIAL_TYPE IN ('ZSPR','ZSPN');

-- C. RAW movement class for the 50 (as-of 2025-12-31 only; no earlier as-of exists in this table)
SELECT AS_OF_DATE, MOVEMENT_CLASS, COUNT(*) N FROM VEDANTA_POC.MATERIAL_PLANT_CLASSIFICATION
WHERE PLANT_ID='HZL_DEMO_05' AND MATERIAL_ID IN (:MATS) GROUP BY AS_OF_DATE, MOVEMENT_CLASS;

-- D. Curated classification for the same 50, reconciliation only (carries GENERATION_SEED, DATA_ORIGIN='DERIVED')
SELECT COUNT(*) N, SUM(AVAILABLE_QTY) QTY, SUM(INVENTORY_VALUE_INR) VAL, MAX(GENERATION_SEED) SEED
FROM VEDANTA_POC.INVENTORY_CLASSIFICATION WHERE PLANT_ID='HZL_DEMO_05' AND AS_OF_DATE='2025-12-31' AND MATERIAL_ID IN (:MATS);

-- E. Curated plant-wide KPI series, reconciliation only (data/raw/curated_kpi_*.csv)
SELECT SNAPSHOT_DATE, KPI_CODE, KPI_VALUE, SCENARIO_LABEL FROM VEDANTA_POC.INVENTORY_KPI_MONTHLY
WHERE PLANT_ID='HZL_DEMO_05' AND KPI_CODE IN ('GROSS_INVENTORY_VALUE_INR','EXCESS_INVENTORY_VALUE_INR','NON_MOVING_VALUE_INR',
  'SLOW_MOVING_VALUE_INR','OBSOLETE_VALUE_INR','PR_COUNT','CRITICAL_SPARE_AVAILABILITY_PCT','DUPLICATE_SKU_OPPORTUNITY_INR');

-- F. Duplicate-SKU candidates: exact description match across all ZSPR/ZSPN (data/raw/duplicate_sku_candidates.csv)
SELECT D.MATERIAL_DESCRIPTION, COUNT(*) N FROM VEDANTA_POC.DIM_MATERIAL D
WHERE D.MATERIAL_TYPE IN ('ZSPR','ZSPN') AND D.MATERIAL_DESCRIPTION IN
  (SELECT MATERIAL_DESCRIPTION FROM VEDANTA_POC.DIM_MATERIAL WHERE MATERIAL_ID IN (:MATS))
GROUP BY D.MATERIAL_DESCRIPTION HAVING COUNT(*) > 1;

-- G. PR lines per material per calendar year, non-cancelled (data/raw/pr_lines_by_material_year.csv)
SELECT MATERIAL_ID, SUBSTR(REQUEST_DATE,1,4) Y, COUNT(*) LINES FROM VEDANTA_POC.FACT_PURCHASE_REQUISITION
WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N' AND STATUS<>'CANCELLED'
  AND REQUEST_DATE>='2024-01-01' AND REQUEST_DATE<='2025-12-31' AND MATERIAL_ID IN (:MATS)
GROUP BY MATERIAL_ID, SUBSTR(REQUEST_DATE,1,4);

-- H. Plan vs actual by month, plant level, ZSPR/ZSPN. The table is keyed by material group, so it cannot be
--    cut to the 50 materials (data/raw/plan_vs_actual_monthly.csv). VARIANCE_INR = PLAN_VALUE_INR - ACTUAL_PO_VALUE_INR
--    (verified month by month, difference under INR 0.1 from rounding).
SELECT SUBSTRING(CALENDAR_MONTH,1,7) M, SUM(TO_DECIMAL(PLAN_VALUE_INR,18,2)) PLAN_V,
       SUM(TO_DECIMAL(ACTUAL_PO_VALUE_INR,18,2)) PO_V, SUM(TO_DECIMAL(ACTUAL_GR_VALUE_INR,18,2)) GR_V,
       SUM(TO_DECIMAL(VARIANCE_INR,18,2)) VAR_V
FROM VEDANTA_POC.BUSINESS_PLAN_VS_ACTUAL WHERE PLANT_ID='HZL_DEMO_05' AND MATERIAL_TYPE IN ('ZSPR','ZSPN')
GROUP BY SUBSTRING(CALENDAR_MONTH,1,7) ORDER BY M;

-- Sections 4, 6, 7, 8 RAW extracts. SELECT only. Plant HZL_DEMO_05, as-of 2025-12-31, IS_BACKCAST_PERIOD='N'.
-- :MATS = the 50 material ids in data/demo_net_issue_series.csv (MATERIAL_PLANT minus the _HZL_DEMO_05 suffix).

-- A. Material master (data/raw/dim_material_50.csv)
SELECT MATERIAL_ID, MATERIAL_TYPE, MATERIAL_GROUP, UNIT_COST_INR, CRITICALITY, SHUTDOWN_MATERIAL_FLAG,
       MIN_ORDER_QTY, ORDER_MULTIPLE, PLANNED_DELIVERY_DAYS, AVG_DAILY_DEMAND, DEMAND_STDDEV_DAILY,
       SAFETY_STOCK_QTY, REORDER_POINT_QTY, MAX_STOCK_QTY, LAST_CONSUMPTION_DATE
FROM VEDANTA_POC.DIM_MATERIAL WHERE MATERIAL_ID IN (:MATS);

-- B. Closing stock and open orders (data/raw/stock_lt_50.csv)
SELECT MATERIAL_ID, CLOSING_QTY, BLOCKED_QTY, IN_TRANSIT_QTY, ON_ORDER_QTY, BACKORDER_QTY, DEMAND_QTY
FROM (SELECT * FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_001 UNION ALL
      SELECT * FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_002 UNION ALL
      SELECT * FROM VEDANTA_POC.FACT_INVENTORY_SNAPSHOT_PART_003)
WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N' AND SNAPSHOT_DATE='2025-12-31' AND MATERIAL_ID IN (:MATS);

-- C. Approved PR awaiting PO per material
SELECT MATERIAL_ID, SUM(TO_DECIMAL(REQUESTED_QTY,18,3)) OPEN_PR_QTY
FROM VEDANTA_POC.FACT_PURCHASE_REQUISITION
WHERE PLANT_ID='HZL_DEMO_05' AND IS_BACKCAST_PERIOD='N' AND STATUS='APPROVED_AWAITING_PO' AND REQUEST_DATE<='2025-12-31'
GROUP BY MATERIAL_ID;

-- D. Median PR->PO days, plant (24 days, 27,387 lines) and actual PO->GR lead time per material
SELECT COUNT(*) N, MEDIAN(DAYS_BETWEEN(TO_DATE(R.REQUEST_DATE), TO_DATE(P.PO_DATE))) MED_PR_PO
FROM VEDANTA_POC.FACT_PURCHASE_ORDER P
JOIN VEDANTA_POC.FACT_PURCHASE_REQUISITION R ON R.PR_NUMBER=P.PR_NUMBER AND R.PR_ITEM=P.PR_ITEM
WHERE R.PLANT_ID='HZL_DEMO_05' AND R.IS_BACKCAST_PERIOD='N' AND P.IS_BACKCAST_PERIOD='N'
  AND R.REQUEST_DATE>='2024-01-01' AND R.REQUEST_DATE<='2025-12-31' AND P.PO_DATE IS NOT NULL;

SELECT R.MATERIAL_ID, AVG(DAYS_BETWEEN(TO_DATE(P.PO_DATE), TO_DATE(G.POSTING_DATE))) ACT_LT
FROM VEDANTA_POC.FACT_GOODS_RECEIPT G
JOIN VEDANTA_POC.FACT_PURCHASE_ORDER P ON P.PO_NUMBER=G.PO_NUMBER AND P.PO_ITEM=G.PO_ITEM
JOIN VEDANTA_POC.FACT_PURCHASE_REQUISITION R ON R.PR_NUMBER=P.PR_NUMBER AND R.PR_ITEM=P.PR_ITEM
WHERE R.PLANT_ID='HZL_DEMO_05' AND R.IS_BACKCAST_PERIOD='N' AND P.IS_BACKCAST_PERIOD='N' AND G.IS_BACKCAST_PERIOD='N'
  AND R.REQUEST_DATE>='2024-01-01' AND R.REQUEST_DATE<='2025-12-31' AND R.MATERIAL_ID IN (:MATS)
GROUP BY R.MATERIAL_ID;

-- E. Shutdowns (data/raw/shutdown_events.csv, shutdown_lines.csv)
SELECT E.SHUTDOWN_ID, E.PLANNED_START_DATE, E.PLANNED_END_DATE, E.STATUS, E.IS_BACKCAST_PERIOD,
       COUNT(S.MATERIAL_ID) LINES, SUM(TO_DECIMAL(S.REQUIRED_QTY,18,3)) REQ
FROM VEDANTA_POC.DIM_SHUTDOWN_EVENT E
LEFT JOIN VEDANTA_POC.FACT_SHUTDOWN_SCHEDULE S ON S.SHUTDOWN_ID=E.SHUTDOWN_ID AND S.MATERIAL_ID IN (:MATS)
WHERE E.PLANT_ID='HZL_DEMO_05'
GROUP BY E.SHUTDOWN_ID, E.PLANNED_START_DATE, E.PLANNED_END_DATE, E.STATUS, E.IS_BACKCAST_PERIOD;

-- F. PR-type mix by month (data/raw/pr_mix_monthly.csv)
SELECT SUBSTR(R.REQUEST_DATE,1,7) M, R.PR_TYPE, COUNT(*) LINES, SUM(TO_DECIMAL(R.REQUESTED_QTY,18,3)) QTY
FROM VEDANTA_POC.FACT_PURCHASE_REQUISITION R
WHERE R.PLANT_ID='HZL_DEMO_05' AND R.IS_BACKCAST_PERIOD='N' AND R.STATUS<>'CANCELLED'
  AND R.REQUEST_DATE>='2024-01-01' AND R.REQUEST_DATE<='2025-12-31' AND R.MATERIAL_ID IN (:MATS)
GROUP BY SUBSTR(R.REQUEST_DATE,1,7), R.PR_TYPE;

-- G. CURATED, reconciliation only
SELECT MATERIAL_ID, MOVEMENT_CLASS, INVENTORY_STATUS, MAX_STOCK_QTY, REORDER_POINT_QTY
FROM VEDANTA_POC.INVENTORY_CLASSIFICATION WHERE PLANT_ID='HZL_DEMO_05' AND AS_OF_DATE='2025-12-31' AND MATERIAL_ID IN (:MATS);
SELECT MATERIAL_ID, RECOMMENDED_QTY, RECOMMENDED_PR_DATE, PRIORITY, SHUTDOWN_ID
FROM VEDANTA_POC.REORDER_RECOMMENDATION WHERE PLANT_ID='HZL_DEMO_05' AND AS_OF_DATE='2025-12-31' AND MATERIAL_ID IN (:MATS);

-- HZL_DEMO demo scope (v3)
-- Plant: HZL_DEMO_05 (highest net issues, ZSPR/ZSPN, Jan 2024-Dec 2025, PART_001-004 UNION ALL)
-- Top 50 material_plants by net issues in that plant over the same window.
-- Monthly net issues (261 issue minus 262 reversal), zero-filled to 50 x 24 = 1,200 rows.
-- Read-only SELECT. Scope: IS_BACKCAST_PERIOD='N', POSTING_DATE 2024-01-01..2025-12-31.
-- QUANTITY and POSTING_DATE are NVARCHAR in the source, so QUANTITY is cast explicitly.
-- Output headers are upper case (MATERIAL_PLANT, MONTH, NET_QTY) as HANA returns them.
-- Verified against RAW (SELECT only): COUNT 1,200; 50 materials; 24 months; 1,046 non-zero rows;
--   top-50 SUM 171,630.000. Partitions are date-contiguous; 1,531,775 source lines, 1,531,775 distinct keys.
WITH SRC AS (
  SELECT PLANT_ID, MATERIAL_ID, MOVEMENT_TYPE, TO_DECIMAL(QUANTITY,18,3) AS Q, POSTING_DATE
  FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_001
  WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE >= '2024-01-01' AND POSTING_DATE <= '2025-12-31'
  UNION ALL
  SELECT PLANT_ID, MATERIAL_ID, MOVEMENT_TYPE, TO_DECIMAL(QUANTITY,18,3), POSTING_DATE
  FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_002
  WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE >= '2024-01-01' AND POSTING_DATE <= '2025-12-31'
  UNION ALL
  SELECT PLANT_ID, MATERIAL_ID, MOVEMENT_TYPE, TO_DECIMAL(QUANTITY,18,3), POSTING_DATE
  FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_003
  WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE >= '2024-01-01' AND POSTING_DATE <= '2025-12-31'
  UNION ALL
  SELECT PLANT_ID, MATERIAL_ID, MOVEMENT_TYPE, TO_DECIMAL(QUANTITY,18,3), POSTING_DATE
  FROM VEDANTA_POC.FACT_MATERIAL_MOVEMENT_PART_004
  WHERE IS_BACKCAST_PERIOD='N' AND MOVEMENT_TYPE IN ('261','262') AND POSTING_DATE >= '2024-01-01' AND POSTING_DATE <= '2025-12-31'
),
SCOPED AS (
  SELECT S.* FROM SRC S
  WHERE S.PLANT_ID = 'HZL_DEMO_05'
    AND S.MATERIAL_ID IN (SELECT MATERIAL_ID FROM VEDANTA_POC.DIM_MATERIAL WHERE MATERIAL_TYPE IN ('ZSPR','ZSPN'))
),
TOP50 AS (
  SELECT MATERIAL_ID FROM (
    SELECT MATERIAL_ID, SUM(CASE WHEN MOVEMENT_TYPE='261' THEN Q ELSE -Q END) AS NET
    FROM SCOPED GROUP BY MATERIAL_ID ORDER BY NET DESC LIMIT 50
  )
),
MONTHLY AS (
  SELECT MATERIAL_ID, SUBSTRING(POSTING_DATE,1,7) AS YM,
         SUM(CASE WHEN MOVEMENT_TYPE='261' THEN Q ELSE -Q END) AS NET_QTY
  FROM SCOPED WHERE MATERIAL_ID IN (SELECT MATERIAL_ID FROM TOP50)
  GROUP BY MATERIAL_ID, SUBSTRING(POSTING_DATE,1,7)
),
MONTHS AS (
  SELECT TO_VARCHAR(ADD_MONTHS(TO_DATE('2024-01-01'), N.N), 'YYYY-MM') AS YM
  FROM (SELECT TOP 24 ROW_NUMBER() OVER () - 1 AS N FROM VEDANTA_POC.DIM_MATERIAL) N
)
SELECT T.MATERIAL_ID || '_HZL_DEMO_05' AS MATERIAL_PLANT,
       M.YM || '-01' AS MONTH,
       COALESCE(MO.NET_QTY, 0) AS NET_QTY
FROM TOP50 T
CROSS JOIN MONTHS M
LEFT JOIN MONTHLY MO ON MO.MATERIAL_ID = T.MATERIAL_ID AND MO.YM = M.YM
ORDER BY MATERIAL_PLANT, MONTH
